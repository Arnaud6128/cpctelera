//-------------------------------------------------------------------------------
//  Cartridge (CPC Plus / GX4000) project, see cfg/cartridge.mk to put files in the banks.
//  The boot (cart/cpct_cart_crt0.s) unlocks the ASIC and copies the program from the bank 0 to the RAM:
//  main() starts with the interrupts disabled and the firmware gone.
//  Remember: the program must not be in 0x0000-0x3FFF (lower ROM) nor in 0x4000-0x7FFF if the ASIC page
//  is connected (cpct_asicPageConnect): keep Z80CODELOC in 0x8000-0xBFFF (cfg/build_config.mk).
//
//  The files of the other banks are read in the ROM of the cartridge, that is seen in two places:
//    * the lower ROM, at 0x0000-0x3FFF: the banks 0-7, chosen with cpct_cartSetLowerRomBank,
//    * the upper ROM, at 0xC000-0xFFFF: the banks 0-31, chosen with cpct_cartSetUpperRomBank.
//  The CPU reads the ROM and the writes go to the RAM under it (the screen, for the upper ROM): a file is
//  copied to the RAM with the ROM enabled. banks.h, written by the build, gives the bank, the offset and the
//  size of each file of cfg/cartridge.mk: CART_<FILE>_BANK / _OFS / _SIZE.
//-------------------------------------------------------------------------------
#include <cpctelera.h>
#include "banks.h"          // CART_<FILE>_BANK / _OFS / _SIZE of the files of cfg/cartridge.mk
#include "g_palette.h"      // palette generated by cfg/image_conversion.mk

/*****************************************************/
/*                                                   */
/*    Read a file of the lower ROM                   */
/*                                                   */
/*****************************************************/
// The bank (0-7) is read at 0x0000 + ofs. The interrupt vector (0x0038) is the one of the bank while the
// lower ROM is enabled: cpct_cartSetLowerRomBank disables the interrupts. Their state is saved before and
// they are enabled again at the end only if they were enabled
void readLowerRom(u8 bank, u16 ofs, void* dst, u16 size)
{
    u8 ints = cpct_areInterruptsEnabled();

    cpct_cartSetLowerRomBank(bank);
    cpct_enableLowerROM();
    cpct_memcpy(dst, (void*)ofs, size);
    cpct_disableLowerROM();
    if (ints)
        cpctm_enableInterrupts();
}

/*****************************************************/
/*                                                   */
/*    Read a file of the upper ROM                   */
/*                                                   */
/*****************************************************/
// The bank (0-31) is read at 0xC000 + ofs: dst must not be in 0xC000-0xFFFF (the screen)
void readUpperRom(u8 bank, u16 ofs, void* dst, u16 size)
{
    cpct_cartSetUpperRomBank(bank);
    cpct_enableUpperROM();
    cpct_memcpy(dst, (void*)(0xC000 + ofs), size);
    cpct_disableUpperROM();
}

/*****************************************************/
/*                                                   */
/*    Main                                           */
/*                                                   */
/*****************************************************/
void main(void)
{
    u8 sprite[CART_SPRITE_SIZE];

    cpct_disableFirmware();                 // Interrupt vector in the RAM (EI : RET)
    cpct_setVideoMode(1);
    cpct_setPalette(g_palette, 4);
    cpct_setBorder(g_palette[0]);
    cpct_memset(CPCT_VMEM_START, 0, 0x4000);

    // The same file (bank 1) is seen by the two windows of the ROM: read with the lower ROM then drawn on the
    // left, the buffer is cleared, read again with the upper ROM and drawn on the right
    // (no firmware ROM on a cartridge: cpct_drawChar/drawString read the font of the firmware, they can not be used)
    readLowerRom(CART_SPRITE_BANK, CART_SPRITE_OFS, sprite, CART_SPRITE_SIZE);
    cpct_drawSprite(sprite, cpct_getScreenPtr(CPCT_VMEM_START, 24, 80), 4, 16);

    cpct_memset(sprite, 0, CART_SPRITE_SIZE);
    readUpperRom(CART_SPRITE_BANK, CART_SPRITE_OFS, sprite, CART_SPRITE_SIZE);
    cpct_drawSprite(sprite, cpct_getScreenPtr(CPCT_VMEM_START, 52, 80), 4, 16);

    while (1);
}