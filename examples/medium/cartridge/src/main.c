//-------------------------------------------------------------------------------
//  Example of the banks of a cartridge (CPC Plus / GX4000), see cfg/cartridge.mk. 
//  The files are generated by cfg/image_conversion.mk (the images and palette), the cartridge only puts them in banks of 16 KB:
//    bank 1     the title (mode 0, 16 KB), read with the upper ROM (0xC000-0xFFFF): it is copied on itself, the CPU
//               reads the ROM and the writes go to the RAM under it (the screen)
//    bank 2     a hardware sprite (CPC Plus), read with the lower ROM (0x0000-0x3FFF, the first 8 banks can be seen there),
//               then copied to the ASIC memory of the sprites
//  The place of each file (bank, offset) is in banks.h, written by the build.
//
//  The boot (cart/cpct_cart_crt0.s) sets the CRTC and unlocks the ASIC. The program runs in the RAM at
//  0x8100: the lower ROM hides 0x0000-0x3FFF and the ASIC registers 0x4000-0x7FFF when connected
//-------------------------------------------------------------------------------

#include <cpctelera.h>
#include "banks.h"                  // CART_<FILE>_BANK / _OFS / _SIZE of the files of cfg/cartridge.mk
#include "g_palette_title.h"        // palette of the title (hardware colours), generated by cfg/image_conversion.mk
#include "g_palette_sprite.h"       // palette of the hardware sprite (ASIC colours)

#define SCREEN_SIZE     0x4000
#define TITLE_COLOURS   16

