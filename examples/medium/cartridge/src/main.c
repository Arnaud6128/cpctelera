// Sprite data local
u8 g_spriteData[HW_SPRITE_SIZE];

/*****************************************************/
/*                                                   */
/*    Show the title read from the ROM               */
/*                                                   */
/*****************************************************/
void showTitle(void)
{
    cpct_setVideoMode(0);
    cpct_setPalette(g_palette_title, TITLE_COLOURS); 
    cpct_setBorder(g_palette_title[0]);

    cpct_cartSetUpperRomBank(CART_TITLE_BANK);          // choose the bank with title screen
    cpct_enableUpperROM();                              // the bank is read at 0xC000-0xFFFF
    cpct_memcpy(CPCT_VMEM_START, CPCT_VMEM_START, SCREEN_SIZE); // Copy from the ROM to the RAM of the screen, RAM is always writable
    cpct_disableUpperROM();                             // the RAM is seen again
}

/*****************************************************/
/*                                                   */
/*    Read the hardware sprite from the ROM          */
/*                                                   */
/*****************************************************/
void loadHwSprite(void)
{
    cpct_cartSetLowerRomBank(CART_HWSPRITE_BANK);       // choose the bank (and disable the interrupts)
    cpct_enableLowerROM();                              // the bank is read at 0x0000
    cpct_memcpy(g_spriteData, (void*)CART_HWSPRITE_OFS, CART_HWSPRITE_SIZE); // Copy to sprite array in RAM
    cpct_disableLowerROM();                             // the RAM is seen again

    cpct_asicPageConnect();                             // the ASIC registers at 0x4000-0x7FFF
    cpct_asicCopySpriteData(0, g_spriteData);           // Copy to Sprite Hardware datas
	
    for (u8 i = 1; i < 4; ++i)                          // Set SH palette
        cpct_asicSetSpritePalColour(i, g_palette_sprite[i]);
		
	// Set mode 0
    cpct_asicSetSpriteZoom(0, HW_SPRITE_MODE_0_ZOOM_X, HW_SPRITE_MODE_0_ZOOM_Y);
}

/*****************************************************/
/*                                                   */
/*    Main                                           */
/*                                                   */
/*****************************************************/
void main(void)
{
    // The crt0 left the mode 1 and both ROMs disabled (cpct_mode_rom_status)
    showTitle();
    loadHwSprite();

    // Place of the sprite in the units of the ASIC
    i16 spriteX = SPRITE_X_START;
    i16 spriteY;
	
	// Step of the wave
    u8 wavePos = 0;
    while (1)
    {
        spriteY = SPRITE_Y_CENTER + _wave[wavePos];
        cpct_waitVSYNC(); 
                                                       
        cpct_asicSetSpritePosition(0, spriteX, spriteY);

        wavePos = (wavePos + 1) & (WAVE_STEPS - 1);
        spriteX += SPRITE_SPEED_X;
        if (spriteX > SPRITE_X_END)
            spriteX = SPRITE_X_START;
    }
}